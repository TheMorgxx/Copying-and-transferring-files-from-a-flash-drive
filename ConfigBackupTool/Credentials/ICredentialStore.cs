namespace ConfigBackupTool.Credentials
{
    // Хранилище "запомненного" пароля бэкапа на этом ПК. Один пароль на пользователя
    // Windows (общий для Export и Restore). Реализация сама решает, как его защищать.
    public interface ICredentialStore
    {
        // true, если пароль сохранён и его удалось прочитать под текущим пользователем.
        bool HasPassword();

        // Возвращает сохранённый пароль или null: файла нет, он пустой или не
        // расшифровывается (создан другим пользователем/ПК). Не бросает на этих случаях.
        string Load();

        // Сохраняет пароль, перезаписывая прежний.
        void Save(string password);

        // Удаляет сохранённый пароль. Если его не было — ничего не делает.
        void Clear();
    }
}
